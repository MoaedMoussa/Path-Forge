import { useState } from 'react';
import { useListLevels, useGetLevelStats } from '@workspace/api-client-react';
import { Link } from 'wouter';
import { Card, Button, Badge } from '../components/ui';
import { Layers, Eye, Calendar, Database, ChevronLeft, ChevronRight } from 'lucide-react';
import { format } from 'date-fns';

export default function Gallery() {
  const [page, setPage] = useState(1);
  const limit = 12;
  
  const { data: listData, isLoading } = useListLevels({ page, limit });
  const { data: stats } = useGetLevelStats();

  return (
    <div className="flex-1 flex flex-col bg-background overflow-y-auto">
      <div className="max-w-6xl w-full mx-auto p-6 md:p-8 space-y-8">
        
        <div className="flex flex-col md:flex-row justify-between items-start md:items-end gap-4 border-b border-border pb-6">
          <div>
            <h1 className="text-3xl font-mono font-bold text-white tracking-tight flex items-center gap-3">
              <Database className="w-8 h-8 text-primary" />
              GLOBAL ARCHIVE
            </h1>
            <p className="text-muted-foreground font-mono text-sm mt-2">Discover computational architectures generated by the network.</p>
          </div>
          
          {stats && (
            <div className="flex gap-4 font-mono text-xs bg-card border border-border p-3 rounded">
              <div className="flex flex-col">
                <span className="text-muted-foreground">TOTAL RECORDS</span>
                <span className="text-white text-base font-bold">{stats.totalLevels}</span>
              </div>
              <div className="w-[1px] bg-border" />
              <div className="flex flex-col">
                <span className="text-muted-foreground">BSP ALGORITHMS</span>
                <span className="text-cyan-400 text-base font-bold">{stats.byAlgorithm['bsp'] || 0}</span>
              </div>
              <div className="flex flex-col">
                <span className="text-muted-foreground">CAVES</span>
                <span className="text-amber-400 text-base font-bold">{stats.byAlgorithm['cellular_automata'] || 0}</span>
              </div>
            </div>
          )}
        </div>

        {isLoading ? (
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
            {[...Array(6)].map((_, i) => (
              <Card key={i} className="h-48 bg-black/50 border-border animate-pulse" />
            ))}
          </div>
        ) : (
          <>
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
              {listData?.levels.map(level => (
                <Card key={level.id} className="bg-card hover:bg-card/80 transition-colors border-border group overflow-hidden flex flex-col">
                  <div className="p-5 flex-1">
                    <div className="flex justify-between items-start mb-4">
                      <Badge variant="outline" className="text-[10px] text-primary border-primary/30 bg-primary/5 uppercase">
                        {level.algorithm.replace('_', ' ')}
                      </Badge>
                      <div className="flex items-center gap-1 text-muted-foreground text-xs font-mono">
                        <Eye className="w-3 h-3" /> {level.viewCount}
                      </div>
                    </div>
                    
                    <div className="space-y-2 font-mono text-sm">
                      <div className="flex justify-between">
                        <span className="text-muted-foreground">DIMENSIONS</span>
                        <span className="text-white">{level.width} × {level.height}</span>
                      </div>
                      <div className="flex justify-between">
                        <span className="text-muted-foreground">SEED</span>
                        <span className="text-white truncate max-w-[120px]">{level.seed}</span>
                      </div>
                      <div className="flex justify-between items-center mt-4">
                        <span className="text-xs text-muted-foreground flex items-center gap-1">
                          <Calendar className="w-3 h-3" /> {format(new Date(level.createdAt), 'MMM dd, yyyy')}
                        </span>
                      </div>
                    </div>
                  </div>
                  <div className="p-4 border-t border-border/50 bg-black/40 mt-auto">
                    <Link href={`/level/${level.slug}`} className="w-full">
                      <Button className="w-full group-hover:bg-primary group-hover:text-primary-foreground transition-all">
                        INITIALIZE SEQUENCE
                      </Button>
                    </Link>
                  </div>
                </Card>
              ))}
            </div>

            {listData && listData.total > limit && (
              <div className="flex justify-center items-center gap-4 mt-8 pt-8 border-t border-border">
                <Button 
                  variant="outline" 
                  size="icon"
                  disabled={page === 1}
                  onClick={() => setPage(p => Math.max(1, p - 1))}
                >
                  <ChevronLeft className="w-4 h-4" />
                </Button>
                <span className="font-mono text-sm text-muted-foreground">
                  PAGE {page} OF {Math.ceil(listData.total / limit)}
                </span>
                <Button 
                  variant="outline" 
                  size="icon"
                  disabled={page >= Math.ceil(listData.total / limit)}
                  onClick={() => setPage(p => p + 1)}
                >
                  <ChevronRight className="w-4 h-4" />
                </Button>
              </div>
            )}
            
            {listData?.levels.length === 0 && (
              <div className="text-center py-20 font-mono text-muted-foreground border border-dashed border-border rounded">
                [ NO RECORDS FOUND IN ARCHIVE ]
              </div>
            )}
          </>
        )}
      </div>
    </div>
  );
}
